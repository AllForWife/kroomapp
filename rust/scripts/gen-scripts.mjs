// The Rust app reuses the Electron app's player-side code as it is (like ios/gen-scripts.mjs does): run `node scripts/gen-scripts.mjs` after
// desktop/keyshift.js changes. Writes js/keyshift.gen.js: __kroomKeyRun(semis, moduleUrl) (keyJs's body) and __KROOM_WORKLET (the AudioWorklet source).
import { createRequire } from 'module';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
const here = path.dirname(fileURLToPath(import.meta.url)), root = path.join(here, '..'), desktop = path.join(root, '..', 'desktop');
const { keyJs, WORKLET } = createRequire(import.meta.url)(path.join(desktop, 'keyshift.js'));
const js = keyJs(0, ''), want = 'const want = 0;', mod = 'const MODULE = "";';
for (const s of [want, mod]) if (js.split(s).length !== 2) throw new Error(`keyshift.js: "${s}" not found once — update scripts/gen-scripts.mjs`);
const body = js.replace(want, 'const want = Math.max(-12, Math.min(12, Math.round(+semis || 0)));').replace(mod, 'const MODULE = String(moduleUrl || "");');
fs.writeFileSync(path.join(root, 'js', 'keyshift.gen.js'), `// generated by scripts/gen-scripts.mjs from desktop/keyshift.js — do not edit\nconst __KROOM_WORKLET = ${JSON.stringify(WORKLET)};\nconst __kroomKeyRun = (semis, moduleUrl) => ${body};\n`);
console.log('js/keyshift.gen.js written');
